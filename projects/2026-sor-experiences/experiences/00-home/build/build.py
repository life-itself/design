#!/usr/bin/env python3
"""Rough stitch of the SoR home page: reads each piece's build/index.html and
writes 00-home/build/index.html. Never hand-edit the output; re-run this."""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent            # .../experiences/00-home/build
EXP = HERE.parent.parent                          # .../experiences
PIECES = [("arrival", "01-arrival"), ("dawn", "02-dawn"), ("leap", "03-leap")]

def grab(html, tag):
    m = re.search(rf"<{tag}\b[^>]*>(.*?)</{tag}>", html, re.S)
    return m.group(1)

def rebase(text, folder):
    """'assets/...' (CSS url(), HTML attrs, JS string/template literals) -> from 00-home/build."""
    return re.sub(r"""(['"`(])assets/""", rf"\1../../{folder}/build/assets/", text)

def piece(name, folder):
    html = (EXP / folder / "build" / "index.html").read_text()
    css, body = grab(html, "style"), grab(html, "body")
    css = re.sub(r"html,\s*body\s*\{[^}]*\}", "", css)       # Dawn: page-level rule
    css = re.sub(r"(?<![\w.-])body\s*\{[^}]*\}", "", css)    # Arrival: body { margin: 0 }
    if name == "leap":
        body = re.sub(r'\s*<section class="x-leap__next".*?</section>', "", body, flags=re.S)
        css = re.sub(r"\s*/\* what follows.*?\.x-leap__next \{.*?\}", "", css, flags=re.S)
        body = body.replace('href="#leap-next"', 'href="#book"')  # "keep learning" -> the Book placeholder
    return f"<!-- ===== {name} ===== -->\n<style>{rebase(css, folder)}</style>\n{rebase(body.strip(), folder)}\n"

PLACEHOLDERS = """<style>
  .x-book-ph, .x-flight-ph { min-height: 200vh; display: grid; place-items: center; text-align: center;
    font: 1.1rem/1.5 "Bricolage Grotesque", system-ui, sans-serif; letter-spacing: .02em; }
  .x-book-ph { background: #080707; color: #efebe4; }
  .x-flight-ph { background: #fbfaf7; color: #121110; }
</style>
"""
BOOK = '<section class="x-book-ph" id="book"><p>4 · The Book — to come</p></section>\n'
FLIGHT = '<section class="x-flight-ph" id="flight"><p>5 · Flight — to come</p></section>\n'

out = ["""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Seeds of Renaissance · home (rough stitch)</title>
<!-- GENERATED by build.py from the pieces' build/index.html. Do not hand-edit. -->
<style>body { margin: 0; }</style>
</head>
<body>
"""]
for name, folder in PIECES:
    out.append(piece(name, folder))
    if name == "leap":
        out.append(PLACEHOLDERS + BOOK + FLIGHT)
out.append("</body>\n</html>\n")
(HERE / "index.html").write_text("\n".join(out))
print("wrote", HERE / "index.html")
