#!/usr/bin/env python3
"""Rough stitch of the SoR home page: reads each piece's build/index.html (or its
sketch/index.html until a build exists) and writes 00-home/build/index.html.
Never hand-edit the output; re-run this.

  python3 build.py               # write index.html here
  python3 build.py --site DIR    # also assemble a static site to publish (see README)"""
import re, shutil, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent            # .../experiences/00-home/build
EXP = HERE.parent.parent                          # .../experiences
PIECES = [("arrival", "01-arrival"), ("dawn", "02-dawn"), ("leap", "03-leap"),
          ("book", "04-book"), ("flight", "05-flight")]

def source(folder):
    """The piece's build/ if it exists, else its rough sketch/."""
    for kind in ("build", "sketch"):
        if (EXP / folder / kind / "index.html").exists():
            return EXP / folder / kind

def grab(html, tag):
    m = re.search(rf"<{tag}\b[^>]*>(.*?)</{tag}>", html, re.S)
    return m.group(1)

def rebase(text, prefix):
    """'assets/...' (CSS url(), HTML attrs, JS string/template literals) -> prefix + 'assets/'."""
    return re.sub(r"""(['"`(])assets/""", rf"\g<1>{prefix}assets/", text)

def piece(name, folder, prefix):
    html = (source(folder) / "index.html").read_text()
    css, body = grab(html, "style"), grab(html, "body")
    css = re.sub(r"html,\s*body\s*\{[^}]*\}", "", css)       # Dawn: page-level rule
    css = re.sub(r"(?<![\w.-])body\s*\{[^}]*\}", "", css)    # Arrival: body { margin: 0 }
    if name == "leap":
        body = re.sub(r'\s*<section class="x-leap__next".*?</section>', "", body, flags=re.S)
        css = re.sub(r"\s*/\* what follows.*?\.x-leap__next \{.*?\}", "", css, flags=re.S)
        body = body.replace('href="#leap-next"', 'href="#book"')  # "keep learning" -> the Book placeholder
    kind = source(folder).name
    return f"<!-- ===== {name} ({folder}/{kind}) ===== -->\n<style>{rebase(css, prefix)}</style>\n{rebase(body.strip(), prefix)}\n"

HEAD = """<title>Seeds of Renaissance Home</title>
<!-- GENERATED by build.py from the pieces' build/ (or sketch/). Do not hand-edit. -->
<style>body { margin: 0; }</style>
"""

def page(prefix_for):
    return "\n".join(piece(n, f, prefix_for(f)) for n, f in PIECES)

out = "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n" \
      "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n" + HEAD + \
      "</head>\n<body>\n" + page(lambda f: f"../../{f}/{source(f).name}/") + "</body>\n</html>\n"
(HERE / "index.html").write_text(out)
print("wrote", HERE / "index.html")

if "--site" in sys.argv:
    # A static site for sharing (published with Flowershow, see 00-home/README.md):
    #   DIR/index.html                the whole page
    #   DIR/<piece>/                  each piece standalone, with its assets (no src/);
    #                                 not under build/, which fl skips
    # Bricolage comes from Google Fonts there, since viewers won't have it installed.
    dest = Path(sys.argv[sys.argv.index("--site") + 1])
    for old in dest.glob("*"):          # keep .flowershow (site name) and other dotfiles
        if not old.name.startswith("."):
            shutil.rmtree(old) if old.is_dir() else old.unlink()
    dest.mkdir(parents=True, exist_ok=True)
    for _, f in PIECES:
        shutil.copytree(source(f), dest / f, ignore=shutil.ignore_patterns("src", "*.py"))
    site = out.replace(page(lambda f: f"../../{f}/{source(f).name}/"), page(lambda f: f"{f}/"))
    site = site.replace(HEAD, HEAD + '<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,400&display=swap">\n')
    site = re.sub(r', url\("[^"]*Polyamine\.ttf"\) format\("truetype"\)', "", site)   # no font file to ship
    (dest / "index.html").write_text(site)
    print("wrote", dest)
